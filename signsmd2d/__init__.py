"""SignSMD-2D: deterministic rule-based compiler from RTMPose COCO-WholeBody
2D keypoints to structured sign-articulation text.

All variants share ONE step-aligned time axis: the compiler first resamples
the clip with EXACTLY the trainer's rule (datasets_signsmd.load_pose,
``--frame_sampling linear``: clips longer than max_length are linearly
downsampled, shorter clips kept whole), then computes evidence on the
resampled sequence and renders every span as ``[step a-b]``.  Step i of the
text is therefore pose token i of the model input, by construction.

- coarse (contract signsmd2d_v0_2): interval prose (realization.py)
- stats  (contract signsmd2d_stats_v0_1): per-channel segmented numeric
  timelines in the style of motion-smd angle_text_v5 (realization_stats.py)
- fingers (contract signsmd2d_fingers_v0_1): compact left/right per-finger
  curl events only (realization_fingers.py)
- parts  (contract signsmd2d_parts_v0_2): per-part (body/left/right/face)
  standalone text files, self-contained events with part-local segmentation,
  plus a structured events/<clip>.json contract for time-aligned injection
  (realization_parts.py, doc/signsmd_part_paired_fusion_plan.md)

Design: motion-smd/HOW2SIGN_JOINT_SMD_DESIGN_2D.md
Consumer: fine_tuning_signsmd.py (docs/POSE_SIGNSMD_FUSION.md)
"""

